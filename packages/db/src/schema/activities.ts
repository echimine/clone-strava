import { sql } from "drizzle-orm";
import {
  boolean,
  doublePrecision,
  index,
  integer,
  jsonb,
  pgSchema,
  primaryKey,
  real,
  smallint,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { user } from "./auth.js";
import { geometryLineString, geometryPoint } from "./postgis.js";
import { sportType } from "./sports.js";

/** `activities` module (ADR-017, ADR-021 §1/§7): the largest module (upload, processing, feed). */
export const activitiesSchema = pgSchema("activities");

export const activityVisibilityEnum = activitiesSchema.enum("visibility", [
  "public",
  "followers",
  "private",
]);

/** ADR-017 + ADR-019 (`pending` -> `processing` -> `processed` | `failed`). */
export const processingStatusEnum = activitiesSchema.enum("processing_status", [
  "pending",
  "processing",
  "processed",
  "failed",
]);

/** ADR-028 §1: where the activity comes from. */
export const activitySourceEnum = activitiesSchema.enum("activity_source", [
  "recorded",
  "imported",
  "manual",
]);

export const importFormatEnum = activitiesSchema.enum("import_format", ["gpx", "tcx", "fit"]);

/** ADR-028 §2. */
export const importStatusEnum = activitiesSchema.enum("import_status", [
  "pending",
  "processing",
  "imported",
  "duplicate",
  "failed",
]);

/** ADR-037 §12: what a Media is. */
export const mediaKindEnum = activitiesSchema.enum("media_kind", ["photo", "video"]);

/** ADR-039 §3: families of Record distances; the two swims are never compared. */
export const recordSetEnum = activitiesSchema.enum("record_set", [
  "run",
  "ride",
  "walk",
  "hike",
  "swim_pool",
  "swim_open_water",
]);

/** ADR-039 §8: the athlete's 1st, 2nd, 3rd time at the date of the Activity. */
export const medalEnum = activitiesSchema.enum("medal", ["gold", "silver", "bronze"]);

export const activity = activitiesSchema.table(
  "activity",
  {
    // No default: the id is generated by the app at recording time (ADR-008, ADR-017).
    id: uuid("id").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    sportTypeCode: text("sport_type_code")
      .notNull()
      .references(() => sportType.code),
    title: text("title").notNull(),
    description: text("description"),
    startedAt: timestamp("started_at", { withTimezone: true }).notNull(),
    endedAt: timestamp("ended_at", { withTimezone: true }).notNull(),
    visibility: activityVisibilityEnum("visibility").notNull().default("public"),
    processingStatus: processingStatusEnum("processing_status").notNull().default("pending"),
    isManual: boolean("is_manual").notNull().default(false),
    source: activitySourceEnum("source").notNull().default("recorded"),
    // ADR-019 §10 (amends ADR-017): processing-tracking columns.
    processingError: text("processing_error"),
    processingAttempts: integer("processing_attempts").notNull().default(0),
    processedAt: timestamp("processed_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    // ADR-033 §2, §4 (amends ADR-017): last metadata change; initialised to `created_at`.
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    // ADR-037 §8: the first Media comes before the map (no effect without a map).
    mediaFirst: boolean("media_first").notNull().default(false),
    // ADR-039 §4: the pool length of a pool swim imported from FIT, in meters (25 yd = 22.86);
    // null when the Activity is not a pool swim.
    poolLengthM: real("pool_length_m"),
  },
  (table) => [
    // ADR-017 "Main indexes": a user's activities, feed.
    index("activity_user_started_at_idx").on(table.userId, table.startedAt.desc()),
    // ADR-017 "Main indexes": resync of in-progress activities (ADR-008), ADR-019 §7 reconciliation.
    index("activity_processing_status_idx")
      .on(table.processingStatus)
      .where(sql`${table.processingStatus} != 'processed'`),
  ],
);

export const activityStats = activitiesSchema.table("activity_stats", {
  activityId: uuid("activity_id")
    .primaryKey()
    .references(() => activity.id, { onDelete: "cascade" }),
  distanceM: real("distance_m"),
  movingTimeS: integer("moving_time_s"),
  elapsedTimeS: integer("elapsed_time_s"),
  elevationGainM: real("elevation_gain_m"),
  avgSpeedMs: real("avg_speed_ms"),
  maxSpeedMs: real("max_speed_ms"),
  avgHeartRate: integer("avg_heart_rate"),
  maxHeartRate: integer("max_heart_rate"),
  calories: integer("calories"),
  // ADR-033 §5 (amends ADR-017): the sport these official values were computed for; differs
  // from `activity.sport_type_code` until `reprocess-activity` has run after a sport change.
  computedForSportTypeCode: text("computed_for_sport_type_code").references(() => sportType.code),
});

export const activityTrack = activitiesSchema.table(
  "activity_track",
  {
    activityId: uuid("activity_id")
      .primaryKey()
      .references(() => activity.id, { onDelete: "cascade" }),
    // Simplified route shown to others; the privacy zone is applied before storage (ADR-019 §5).
    route: geometryLineString("route"),
    startPoint: geometryPoint("start_point"),
    rawPointsS3Key: text("raw_points_s3_key"),
    mapThumbnailUrl: text("map_thumbnail_url"),
    pointCount: integer("point_count"),
    // ADR-029: polyline5 of `route`, simplified to fit a static map URL (≤ 2000 chars).
    mapPolyline: text("map_polyline"),
    // ADR-029: reverse-geocoded place of the (privacy-zoned) start point, e.g. "Annecy, Haute-Savoie".
    locationName: text("location_name"),
    // ADR-036 §5: true when the privacy zone removed at least one point of `route`.
    routeTrimmed: boolean("route_trimmed").notNull().default(false),
  },
  (table) => [
    // ADR-017 "Main indexes": spatial search, segment detection.
    index("activity_track_route_gist_idx").using("gist", table.route),
    index("activity_track_start_point_gist_idx").using("gist", table.startPoint),
  ],
);

/**
 * ADR-036 §6: the Activity analysis (splits and series), computed by the worker on the cleaned
 * trace before the privacy zone. `version` is the code's `ACTIVITY_ANALYSIS_VERSION`; a lower
 * one is picked again by the backfill (§7).
 */
export const activityAnalysis = activitiesSchema.table("activity_analysis", {
  activityId: uuid("activity_id")
    .primaryKey()
    .references(() => activity.id, { onDelete: "cascade" }),
  version: smallint("version").notNull(),
  splits: jsonb("splits").notNull(),
  series: jsonb("series"),
  computedAt: timestamp("computed_at", { withTimezone: true }).notNull().defaultNow(),
});

/**
 * ADR-037 §3, §12: a photo or video of an Activity. A row exists only once
 * the Media is confirmed (ready); `s3_key` is the Media's folder
 * `activities/{userId}/{activityId}/media/{mediaId}/`. Dimensions and
 * duration come from the phone; `duration_ms` is null for a photo.
 */
export const activityMedia = activitiesSchema.table(
  "activity_media",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    activityId: uuid("activity_id")
      .notNull()
      .references(() => activity.id, { onDelete: "cascade" }),
    s3Key: text("s3_key").notNull(),
    kind: mediaKindEnum("kind").notNull(),
    width: integer("width").notNull(),
    height: integer("height").notNull(),
    durationMs: integer("duration_ms"),
    position: integer("position").notNull().default(0),
    // ADR-037 §14: stays unused (no photo locations on the map).
    takenAtPoint: geometryPoint("taken_at_point"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    // ADR-037 §8: read order `(position, created_at)` within an Activity.
    index("activity_media_activity_position_idx").on(
      table.activityId,
      table.position,
      table.createdAt,
    ),
  ],
);

/** ADR-028 §1: import of a .gpx / .tcx / .fit file. */
export const activityImport = activitiesSchema.table(
  "activity_import",
  {
    // No default: the id is generated by the app when the file is picked (ADR-028 §1).
    id: uuid("id").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    format: importFormatEnum("format").notNull(),
    originalFileName: text("original_file_name").notNull(),
    sizeBytes: integer("size_bytes").notNull(),
    sha256: text("sha256"),
    status: importStatusEnum("status").notNull().default("pending"),
    // Created activity (`imported`) or existing one (`duplicate`).
    activityId: uuid("activity_id").references(() => activity.id, { onDelete: "set null" }),
    requestedSportTypeCode: text("requested_sport_type_code").references(() => sportType.code),
    requestedTitle: text("requested_title"),
    requestedVisibility: activityVisibilityEnum("requested_visibility"),
    error: text("error"),
    attempts: integer("attempts").notNull().default(0),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    processedAt: timestamp("processed_at", { withTimezone: true }),
  },
  (table) => [
    index("activity_import_user_created_at_idx").on(table.userId, table.createdAt.desc()),
    // ADR-028 §6: the database refuses a second import of the same content.
    uniqueIndex("activity_import_user_sha256_imported_idx")
      .on(table.userId, table.sha256)
      .where(sql`${table.status} = 'imported'`),
    // ADR-028 §8: reconciliation of imports left in flight.
    index("activity_import_status_idx")
      .on(table.status)
      .where(sql`${table.status} in ('pending', 'processing')`),
  ],
);

/**
 * ADR-039 §3, §17: the Best effort of an Activity over one Record distance, upserted by the
 * processing transaction. The Record is the minimum over the athlete's rows not removed;
 * `medal` is replayed in date order whenever their history changes (§8). `removed_at` is set
 * by the athlete, for good: a recomputation never clears it.
 */
export const bestEffort = activitiesSchema.table(
  "best_effort",
  {
    activityId: uuid("activity_id")
      .notNull()
      .references(() => activity.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    recordSet: recordSetEnum("record_set").notNull(),
    // Meters; the half marathon is 21,097.5.
    distanceM: doublePrecision("distance_m").notNull(),
    elapsedTimeMs: integer("elapsed_time_ms").notNull(),
    startDistanceM: real("start_distance_m").notNull(),
    // Copied from the Activity: the Medals are replayed in this order.
    activityStartedAt: timestamp("activity_started_at", { withTimezone: true }).notNull(),
    medal: medalEnum("medal"),
    removedAt: timestamp("removed_at", { withTimezone: true }),
  },
  (table) => [
    primaryKey({ columns: [table.activityId, table.distanceM] }),
    // The athlete's Record and Medals on one distance.
    index("best_effort_user_set_distance_time_idx").on(
      table.userId,
      table.recordSet,
      table.distanceM,
      table.elapsedTimeMs,
    ),
  ],
);
