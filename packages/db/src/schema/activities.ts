import { sql } from "drizzle-orm";
import {
  boolean,
  index,
  integer,
  pgSchema,
  real,
  text,
  timestamp,
  uuid,
} from "drizzle-orm/pg-core";
import { user } from "./auth.js";
import { geometryLineString, geometryPoint } from "./postgis.js";
import { sportType } from "./sports.js";

/** `activities` module (ADR-017, ADR-021 §1/§7): the largest module (upload, processing, feed). */
export const activitiesSchema = pgSchema("activities");

export const activityVisibilityEnum = activitiesSchema.enum("visibility", [
  "public",
  "followers",
  "private",
]);

/** ADR-017 + ADR-019 (`pending` -> `processing` -> `processed` | `failed`). */
export const processingStatusEnum = activitiesSchema.enum("processing_status", [
  "pending",
  "processing",
  "processed",
  "failed",
]);

export const attachmentKindEnum = activitiesSchema.enum("attachment_kind", ["photo", "video"]);

export const activity = activitiesSchema.table(
  "activity",
  {
    // No default: the id is generated by the app at recording time (ADR-008, ADR-017).
    id: uuid("id").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    sportTypeCode: text("sport_type_code")
      .notNull()
      .references(() => sportType.code),
    title: text("title").notNull(),
    description: text("description"),
    startedAt: timestamp("started_at", { withTimezone: true }).notNull(),
    endedAt: timestamp("ended_at", { withTimezone: true }).notNull(),
    visibility: activityVisibilityEnum("visibility").notNull().default("public"),
    processingStatus: processingStatusEnum("processing_status").notNull().default("pending"),
    isManual: boolean("is_manual").notNull().default(false),
    // ADR-019 §10 (amends ADR-017): processing-tracking columns.
    processingError: text("processing_error"),
    processingAttempts: integer("processing_attempts").notNull().default(0),
    processedAt: timestamp("processed_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    // ADR-017 "Main indexes": a user's activities, feed.
    index("activity_user_started_at_idx").on(table.userId, table.startedAt.desc()),
    // ADR-017 "Main indexes": resync of in-progress activities (ADR-008), ADR-019 §7 reconciliation.
    index("activity_processing_status_idx")
      .on(table.processingStatus)
      .where(sql`${table.processingStatus} != 'processed'`),
  ],
);

export const activityStats = activitiesSchema.table("activity_stats", {
  activityId: uuid("activity_id")
    .primaryKey()
    .references(() => activity.id, { onDelete: "cascade" }),
  distanceM: real("distance_m"),
  movingTimeS: integer("moving_time_s"),
  elapsedTimeS: integer("elapsed_time_s"),
  elevationGainM: real("elevation_gain_m"),
  avgSpeedMs: real("avg_speed_ms"),
  maxSpeedMs: real("max_speed_ms"),
  avgHeartRate: integer("avg_heart_rate"),
  maxHeartRate: integer("max_heart_rate"),
  calories: integer("calories"),
});

export const activityTrack = activitiesSchema.table(
  "activity_track",
  {
    activityId: uuid("activity_id")
      .primaryKey()
      .references(() => activity.id, { onDelete: "cascade" }),
    // Simplified route shown to others; the privacy zone is applied before storage (ADR-019 §5).
    route: geometryLineString("route"),
    startPoint: geometryPoint("start_point"),
    rawPointsS3Key: text("raw_points_s3_key"),
    mapThumbnailUrl: text("map_thumbnail_url"),
    pointCount: integer("point_count"),
  },
  (table) => [
    // ADR-017 "Main indexes": spatial search, segment detection.
    index("activity_track_route_gist_idx").using("gist", table.route),
    index("activity_track_start_point_gist_idx").using("gist", table.startPoint),
  ],
);

export const activityAttachment = activitiesSchema.table("activity_attachment", {
  id: uuid("id").defaultRandom().primaryKey(),
  activityId: uuid("activity_id")
    .notNull()
    .references(() => activity.id, { onDelete: "cascade" }),
  s3Key: text("s3_key").notNull(),
  kind: attachmentKindEnum("kind").notNull(),
  position: integer("position").notNull().default(0),
  takenAtPoint: geometryPoint("taken_at_point"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});
