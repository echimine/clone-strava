import { index, integer, pgSchema, primaryKey, real, text, timestamp, uuid } from "drizzle-orm/pg-core";
import { user } from "./auth.js";
import { geometryLineString, geometryLineStringZ, geometryPoint } from "./postgis.js";
import { sportType } from "./sports.js";

/**
 * `itineraries` module (ADR-030 §4, §5, amends ADR-017): Itineraries
 * planned by hand, private to their creator.
 */
export const itinerariesSchema = pgSchema("itineraries");

/** ADR-030 §3: where the altitudes of `track` come from. */
export const itineraryElevationSourceEnum = itinerariesSchema.enum("elevation_source", [
  "ign",
  "mixed",
  "open_meteo",
]);

/** ADR-030 §2: a Leg follows roads and trails, or runs straight. */
export const itineraryLegModeEnum = itinerariesSchema.enum("leg_mode", ["follow", "straight"]);

export const itinerary = itinerariesSchema.table(
  "itinerary",
  {
    // No default: the id is generated by the app (ADR-030 §5, idempotent `POST`).
    id: uuid("id").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    sportTypeCode: text("sport_type_code")
      .notNull()
      .references(() => sportType.code),
    // 1 to 100 characters, trimmed by the API.
    name: text("name").notNull(),
    distanceM: real("distance_m").notNull(),
    elevationGainM: real("elevation_gain_m").notNull(),
    elevationSource: itineraryElevationSourceEnum("elevation_source").notNull(),
    // Points resampled every ~20 m, Z = altitude. No GiST index: never searched spatially (ADR-030 §5).
    track: geometryLineStringZ("track").notNull(),
    // ADR-029: polyline5 of the track, simplified to fit a static map URL (≤ 2000 chars).
    mapPolyline: text("map_polyline").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    // ADR-030 §5: the athlete's list, keyset on `(updated_at desc, id)`.
    index("itinerary_user_updated_at_idx").on(table.userId, table.updatedAt.desc(), table.id),
  ],
);

/** Waypoints in order; replaced entirely on every full update (ADR-030 §5). */
export const itineraryWaypoint = itinerariesSchema.table(
  "itinerary_waypoint",
  {
    itineraryId: uuid("itinerary_id")
      .notNull()
      .references(() => itinerary.id, { onDelete: "cascade" }),
    position: integer("position").notNull(),
    // Snapped position when routing snapped the Waypoint (ADR-030 §2).
    location: geometryPoint("location").notNull(),
  },
  (table) => [primaryKey({ columns: [table.itineraryId, table.position] })],
);

/** Leg n joins Waypoints n and n+1; replaced entirely on every full update (ADR-030 §5). */
export const itineraryLeg = itinerariesSchema.table(
  "itinerary_leg",
  {
    itineraryId: uuid("itinerary_id")
      .notNull()
      .references(() => itinerary.id, { onDelete: "cascade" }),
    position: integer("position").notNull(),
    mode: itineraryLegModeEnum("mode").notNull(),
    // 2D: the Mapbox geometry of a `follow` Leg, the server-drawn segment of a `straight` one.
    path: geometryLineString("path").notNull(),
  },
  (table) => [primaryKey({ columns: [table.itineraryId, table.position] })],
);
