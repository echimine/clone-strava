import { z } from "zod";
import { sportTypeCodeSchema } from "../sports/sport-type.js";
import { itineraryGeometrySchema, itineraryLegModeSchema, itineraryWaypointSchema } from "./geometry.js";
import { itineraryMetricsSchema } from "./metrics-preview.js";

/** An Itinerary's name (ADR-030 §5): 1 to 100 characters once trimmed. */
export const itineraryNameSchema = z.string().trim().min(1).max(100);

/**
 * Name, sport and geometry of an Itinerary: the body of a full save
 * (ADR-030 §6). The sport must exist and not be a `water` one (`422`).
 */
export const saveItineraryRequestSchema = itineraryGeometrySchema.extend({
  name: itineraryNameSchema,
  sportTypeCode: sportTypeCodeSchema,
});
export type SaveItineraryRequest = z.infer<typeof saveItineraryRequestSchema>;

/**
 * `POST /v1/itineraries` body (ADR-030 §6): the id is generated by the
 * app, so a replayed call is recognised (`200`, nothing written).
 */
export const createItineraryRequestSchema = saveItineraryRequestSchema.extend({ id: z.uuid() });
export type CreateItineraryRequest = z.infer<typeof createItineraryRequestSchema>;

/**
 * `PATCH /v1/itineraries/:id` body (ADR-030 §6): renaming outside the
 * editor, with no recomputation.
 */
export const renameItineraryRequestSchema = z.object({ name: itineraryNameSchema });
export type RenameItineraryRequest = z.infer<typeof renameItineraryRequestSchema>;

/**
 * A stored Leg: its mode and its 2D path as polyline6 (the Mapbox geometry
 * of a `follow` Leg, the server-drawn segment of a `straight` one).
 */
export const itineraryLegDetailSchema = z.object({
  mode: itineraryLegModeSchema,
  polyline6: z.string().min(1),
});
export type ItineraryLegDetail = z.infer<typeof itineraryLegDetailSchema>;

/**
 * The stored track (ADR-030 §3): points every ~20 m as polyline6, and
 * their altitudes in meters, one per point, for the elevation profile.
 */
export const itineraryTrackSchema = z.object({
  polyline6: z.string().min(1),
  altitudesM: z.array(z.number()),
});
export type ItineraryTrack = z.infer<typeof itineraryTrackSchema>;

/**
 * `GET /v1/itineraries/:id` response, also returned by a save (ADR-030 §6).
 * `distanceM`, `elevationGainM` and `elevationSource` equal what
 * `metrics-preview` answers for the same Waypoints and Legs.
 */
export const itinerarySchema = itineraryMetricsSchema.extend({
  id: z.uuid(),
  name: z.string(),
  sportTypeCode: sportTypeCodeSchema,
  waypoints: z.array(itineraryWaypointSchema),
  legs: z.array(itineraryLegDetailSchema),
  track: itineraryTrackSchema,
  createdAt: z.iso.datetime(),
  updatedAt: z.iso.datetime(),
});
export type Itinerary = z.infer<typeof itinerarySchema>;

/** `GET /v1/itineraries` query (ADR-030 §6): opaque keyset cursor, no page numbers. */
export const listItinerariesQuerySchema = z.object({
  cursor: z.string().min(1).max(200).optional(),
  limit: z.coerce.number().int().min(1).max(50).default(20),
});
export type ListItinerariesQuery = z.infer<typeof listItinerariesQuerySchema>;

/** One row of the athlete's Itinerary list; `mapPolyline` is polyline5 (ADR-029). */
export const itinerarySummarySchema = z.object({
  id: z.uuid(),
  name: z.string(),
  sportTypeCode: sportTypeCodeSchema,
  distanceM: z.number().nonnegative(),
  elevationGainM: z.number().nonnegative(),
  mapPolyline: z.string().min(1),
  updatedAt: z.iso.datetime(),
});
export type ItinerarySummary = z.infer<typeof itinerarySummarySchema>;

/**
 * `GET /v1/itineraries` response: the athlete's Itineraries, most
 * recently updated first; `nextCursor` is null on the last page.
 */
export const listItinerariesResponseSchema = z.object({
  items: z.array(itinerarySummarySchema),
  nextCursor: z.string().min(1).nullable(),
});
export type ListItinerariesResponse = z.infer<typeof listItinerariesResponseSchema>;
