import { z } from "zod";
import { itineraryElevationSourceSchema } from "../itineraries/geometry.js";

/**
 * Typed analytics event catalog (ADR-015 "Event naming and catalog"):
 * reliable, backend-emitted events only (`api`/`worker`, via `posthog-node`).
 * `object_action`, snake_case, past tense; no free-form strings in
 * application code.
 */
export const ANALYTICS_EVENTS = {
  ACTIVITY_PROCESSED: "activity_processed",
  ACTIVITY_FAILED: "activity_failed",
  ACTIVITY_IMPORTED: "activity_imported",
  ACTIVITY_IMPORT_FAILED: "activity_import_failed",
  /** Itinerary lifecycle, emitted by the API (ADR-030 §10, catalog of issue #20). */
  ITINERARY_CREATED: "itinerary_created",
  ITINERARY_UPDATED: "itinerary_updated",
  ITINERARY_RENAMED: "itinerary_renamed",
  ITINERARY_DELETED: "itinerary_deleted",
  ITINERARY_SAVE_FAILED: "itinerary_save_failed",
} as const;
export type AnalyticsEventName = (typeof ANALYTICS_EVENTS)[keyof typeof ANALYTICS_EVENTS];

/** No personal data (ADR-015 "Data sent"): sport type only, never GPS, route or photo. */
export const activityProcessedPropertiesSchema = z.object({
  sportTypeCode: z.string(),
});
export type ActivityProcessedProperties = z.infer<typeof activityProcessedPropertiesSchema>;

export const activityFailedPropertiesSchema = z.object({
  sportTypeCode: z.string().optional(),
  errorCode: z.string(),
});
export type ActivityFailedProperties = z.infer<typeof activityFailedPropertiesSchema>;

/** ADR-028 §4 step 11: file format and resolved sport, never the file name or content. */
export const activityImportedPropertiesSchema = z.object({
  format: z.string(),
  sportTypeCode: z.string(),
});
export type ActivityImportedProperties = z.infer<typeof activityImportedPropertiesSchema>;

export const activityImportFailedPropertiesSchema = z.object({
  format: z.string(),
  errorCode: z.string(),
});
export type ActivityImportFailedProperties = z.infer<typeof activityImportFailedPropertiesSchema>;

/**
 * `itinerary_created` / `itinerary_updated`: the full set (ADR-030 §10),
 * rounded, never a coordinate. `itineraryId` is generated by the app, so it
 * links the app's and the API's events.
 */
export const itinerarySavedPropertiesSchema = z.object({
  itineraryId: z.uuid(),
  sportTypeCode: z.string(),
  sportCategory: z.enum(["foot", "wheels"]),
  waypointCount: z.int(),
  /** Share of `straight` Legs, rounded to 0.1. */
  straightLegRatio: z.number(),
  /** Whole kilometers. */
  distanceKm: z.int(),
  /** Rounded to 10 m. */
  elevationGainM: z.int(),
  elevationSource: itineraryElevationSourceSchema,
});
export type ItinerarySavedProperties = z.infer<typeof itinerarySavedPropertiesSchema>;

/** `itinerary_renamed` / `itinerary_deleted`. */
export const itineraryRefPropertiesSchema = z.object({
  itineraryId: z.uuid(),
});
export type ItineraryRefProperties = z.infer<typeof itineraryRefPropertiesSchema>;

/** A save (create or full update) that failed, e.g. `elevation_unavailable` (`503`). */
export const itinerarySaveFailedPropertiesSchema = z.object({
  errorCode: z.string(),
});
export type ItinerarySaveFailedProperties = z.infer<typeof itinerarySaveFailedPropertiesSchema>;

/** Payload schema for a given catalog event, keyed by its name. */
export const analyticsEventPropertiesSchemas = {
  [ANALYTICS_EVENTS.ACTIVITY_PROCESSED]: activityProcessedPropertiesSchema,
  [ANALYTICS_EVENTS.ACTIVITY_FAILED]: activityFailedPropertiesSchema,
  [ANALYTICS_EVENTS.ACTIVITY_IMPORTED]: activityImportedPropertiesSchema,
  [ANALYTICS_EVENTS.ACTIVITY_IMPORT_FAILED]: activityImportFailedPropertiesSchema,
  [ANALYTICS_EVENTS.ITINERARY_CREATED]: itinerarySavedPropertiesSchema,
  [ANALYTICS_EVENTS.ITINERARY_UPDATED]: itinerarySavedPropertiesSchema,
  [ANALYTICS_EVENTS.ITINERARY_RENAMED]: itineraryRefPropertiesSchema,
  [ANALYTICS_EVENTS.ITINERARY_DELETED]: itineraryRefPropertiesSchema,
  [ANALYTICS_EVENTS.ITINERARY_SAVE_FAILED]: itinerarySaveFailedPropertiesSchema,
} as const satisfies Record<AnalyticsEventName, z.ZodType>;
