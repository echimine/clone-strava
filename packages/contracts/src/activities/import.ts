import { z } from "zod";
import { visibilitySchema } from "../common/enums.js";
import { sportTypeCodeSchema } from "../sports/sport-type.js";
import { uploadUrlResponseSchema } from "./activity.js";

/** `activity_import.format` (ADR-028 §1). */
export const activityImportFormatSchema = z.enum(["gpx", "tcx", "fit"]);
export type ActivityImportFormat = z.infer<typeof activityImportFormatSchema>;

/** `activity_import.status` (ADR-028 §2). */
export const activityImportStatusSchema = z.enum([
  "pending",
  "processing",
  "imported",
  "duplicate",
  "failed",
]);
export type ActivityImportStatus = z.infer<typeof activityImportStatusSchema>;

/** `activity_import.error` codes (ADR-028 §7). */
export const activityImportErrorCodeSchema = z.enum([
  "invalid_file",
  "unsupported_format",
  "no_timestamps",
  "no_gps_data",
  "empty_track",
  "too_many_points",
  "invalid_duration",
  "unknown_sport",
  "processing_error",
]);
export type ActivityImportErrorCode = z.infer<typeof activityImportErrorCodeSchema>;

/** ADR-028 §11. */
export const ACTIVITY_IMPORT_MAX_FILE_BYTES = 25 * 1024 * 1024;
export const ACTIVITY_IMPORT_MAX_POINTS = 200_000;
/** ADR-028 §9: imports per user per hour. */
export const ACTIVITY_IMPORT_RATE_LIMIT_PER_HOUR = 30;

/** Bucket key of an import's original file (ADR-028 §3). */
export function activityImportSourceKey(
  userId: string,
  importId: string,
  format: ActivityImportFormat,
): string {
  return `imports/${userId}/${importId}/source.${format}`;
}

/** `POST /v1/activity-imports` request body (ADR-028 §3). */
export const createActivityImportRequestSchema = z
  .object({
    /** Generated by the app when the file is picked (ADR-028 §1). */
    id: z.uuid(),
    format: activityImportFormatSchema,
    fileName: z.string().min(1).max(255),
    sizeBytes: z.number().int().positive().max(ACTIVITY_IMPORT_MAX_FILE_BYTES),
    sportTypeCode: sportTypeCodeSchema.optional(),
    title: z.string().min(1).max(255).optional(),
    visibility: visibilitySchema.optional(),
  })
  .refine((body) => body.fileName.toLowerCase().endsWith(`.${body.format}`), {
    path: ["fileName"],
    message: "The file extension does not match the declared format",
  });
export type CreateActivityImportRequest = z.infer<typeof createActivityImportRequestSchema>;

/** Wire representation of an import. */
export const activityImportSchema = z.object({
  id: z.uuid(),
  format: activityImportFormatSchema,
  fileName: z.string(),
  status: activityImportStatusSchema,
  /** Created activity (`imported`) or existing one (`duplicate`). */
  activityId: z.uuid().optional(),
  error: activityImportErrorCodeSchema.optional(),
  createdAt: z.iso.datetime(),
  processedAt: z.iso.datetime().optional(),
});
export type ActivityImport = z.infer<typeof activityImportSchema>;

/** `POST /v1/activity-imports` response: `upload` only while `pending`. */
export const createActivityImportResponseSchema = z.object({
  import: activityImportSchema,
  upload: uploadUrlResponseSchema.optional(),
});
export type CreateActivityImportResponse = z.infer<typeof createActivityImportResponseSchema>;

/** `POST /v1/activity-imports/:id/complete` response (`202`). */
export const completeActivityImportResponseSchema = z.object({
  import: activityImportSchema,
});
export type CompleteActivityImportResponse = z.infer<typeof completeActivityImportResponseSchema>;

/** `GET /v1/activity-imports?status=` query. */
export const listActivityImportsQuerySchema = z.object({
  status: activityImportStatusSchema.optional(),
  page: z.coerce.number().int().min(1).default(1),
  limit: z.coerce.number().int().min(1).max(100).default(20),
});
export type ListActivityImportsQuery = z.infer<typeof listActivityImportsQuerySchema>;

export const listActivityImportsResponseSchema = z.object({
  items: z.array(activityImportSchema),
  page: z.number().int(),
  limit: z.number().int(),
  total: z.number().int(),
});
export type ListActivityImportsResponse = z.infer<typeof listActivityImportsResponseSchema>;
