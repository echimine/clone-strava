import { z } from "zod";
import { processingStatusSchema, visibilitySchema } from "../common/enums.js";
import { sportTypeCodeSchema } from "../sports/sport-type.js";
import { feedActivityMapSchema, feedAuthorSchema, feedEngagementSchema } from "./feed.js";

/** Provisional values computed by the app (ADR-019 §1): compared, never trusted, by the worker. */
export const provisionalActivityValuesSchema = z.object({
  distanceM: z.number().nonnegative().optional(),
  movingTimeS: z.number().int().nonnegative().optional(),
  elapsedTimeS: z.number().int().nonnegative().optional(),
  elevationGainM: z.number().nonnegative().optional(),
});
export type ProvisionalActivityValues = z.infer<typeof provisionalActivityValuesSchema>;

/**
 * `POST /v1/activities` request body (ADR-019 §1). `id` is generated by the
 * app at the start of recording (ADR-008, ADR-017), not by the server.
 */
export const createActivityRequestSchema = z
  .object({
    id: z.uuid(),
    sportTypeCode: sportTypeCodeSchema,
    title: z.string().min(1).max(255),
    description: z.string().max(10_000).optional(),
    startedAt: z.iso.datetime(),
    endedAt: z.iso.datetime(),
    visibility: visibilitySchema,
    isManual: z.boolean(),
    ...provisionalActivityValuesSchema.shape,
  })
  .refine((body) => Date.parse(body.endedAt) > Date.parse(body.startedAt), {
    path: ["endedAt"],
    message: "endedAt must be after startedAt",
  });
export type CreateActivityRequest = z.infer<typeof createActivityRequestSchema>;

/** Minimal activity representation returned by the creation/completion endpoints. */
export const activitySummarySchema = z.object({
  id: z.uuid(),
  sportTypeCode: sportTypeCodeSchema,
  visibility: visibilitySchema,
  processingStatus: processingStatusSchema,
});
export type ActivitySummary = z.infer<typeof activitySummarySchema>;

/** Pre-signed upload URL (ADR-019 §1-2): 15 minutes, `PUT` to the bucket. */
export const uploadUrlResponseSchema = z.object({
  uploadUrl: z.url(),
  expiresAt: z.iso.datetime(),
});
export type UploadUrlResponse = z.infer<typeof uploadUrlResponseSchema>;

/**
 * `POST /v1/activities` response (ADR-019 §1): `201` for a new activity,
 * `200` for a replayed call. `upload` is absent once the activity is no
 * longer `pending`.
 */
export const createActivityResponseSchema = z.object({
  activity: activitySummarySchema,
  upload: uploadUrlResponseSchema.optional(),
});
export type CreateActivityResponse = z.infer<typeof createActivityResponseSchema>;

/** `POST /v1/activities/:id/upload-url` response (ADR-019 §2): URL renewal. */
export const renewUploadUrlResponseSchema = uploadUrlResponseSchema;
export type RenewUploadUrlResponse = z.infer<typeof renewUploadUrlResponseSchema>;

/** `POST /v1/activities/:id/complete` response (ADR-019 §4): `202 Accepted`. */
export const completeActivityResponseSchema = z.object({
  activity: activitySummarySchema,
});
export type CompleteActivityResponse = z.infer<typeof completeActivityResponseSchema>;

/** `activity.processing_error` codes (ADR-019 §6): why the worker failed the activity. */
export const activityProcessingErrorCodeSchema = z.enum(["invalid_trace", "empty_trace", "processing_error"]);
export type ActivityProcessingErrorCode = z.infer<typeof activityProcessingErrorCodeSchema>;

/** Official values computed by the worker (ADR-019 §5); null when not computed or not tracked by the sport. */
export const activityStatsSchema = z.object({
  distanceM: z.number().nullable(),
  movingTimeS: z.number().int().nullable(),
  elapsedTimeS: z.number().int().nullable(),
  elevationGainM: z.number().nullable(),
  avgSpeedMs: z.number().nullable(),
  maxSpeedMs: z.number().nullable(),
  avgHeartRate: z.number().int().nullable(),
  maxHeartRate: z.number().int().nullable(),
  calories: z.number().int().nullable(),
});
export type ActivityStats = z.infer<typeof activityStatsSchema>;

/**
 * `GET /v1/activities/:id` response (ADR-033 §2, amends ADR-031 §13): any
 * viewer who can see the Activity. The author gets it in any state, others
 * only once `processed`. `stats` holds the official values once
 * `processed`, null before; `processingError` is present only once
 * `failed`. Author and engagement are assembled like a feed card (ADR-029 §2).
 */
export const activityDetailSchema = z.object({
  id: z.uuid(),
  title: z.string(),
  // Optional rather than nullable: @nestjs/swagger reads a top-level `type: ["string", "null"]` as an array.
  description: z.string().optional(),
  sportTypeCode: sportTypeCodeSchema,
  startedAt: z.iso.datetime(),
  endedAt: z.iso.datetime(),
  visibility: visibilitySchema,
  processingStatus: processingStatusSchema,
  processingError: activityProcessingErrorCodeSchema.optional(),
  // Optional for the same reason as `description`: absent until the place is known.
  locationName: z.string().optional(),
  stats: activityStatsSchema.nullable(),
  map: feedActivityMapSchema.nullable(),
  author: feedAuthorSchema,
  engagement: feedEngagementSchema,
  viewerIsAuthor: z.boolean(),
  updatedAt: z.iso.datetime(),
});
export type ActivityDetail = z.infer<typeof activityDetailSchema>;
