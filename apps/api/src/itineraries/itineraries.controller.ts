import { Body, Controller, Get, HttpCode, HttpStatus, Param, ParseUUIDPipe, Post, Query, Res, UseGuards } from "@nestjs/common";
import { ApiResponse } from "@nestjs/swagger";
import type { Response } from "express";
import { createZodDto, ZodResponse } from "nestjs-zod";
import {
  createItineraryRequestSchema,
  itineraryMetricsPreviewRequestSchema,
  itineraryMetricsSchema,
  itinerarySchema,
  listItinerariesQuerySchema,
  listItinerariesResponseSchema,
  type Itinerary,
  type ItineraryMetrics,
  type ListItinerariesResponse,
} from "@repo/contracts";
import { ItinerariesService } from "@repo/core/itineraries";
import { CurrentUser } from "../auth/current-user.decorator.js";
import { SessionGuard, type AuthenticatedUser } from "../auth/session.guard.js";

class ItineraryMetricsPreviewRequestDto extends createZodDto(itineraryMetricsPreviewRequestSchema) {}
class ItineraryMetricsDto extends createZodDto(itineraryMetricsSchema) {}
class CreateItineraryRequestDto extends createZodDto(createItineraryRequestSchema) {}
class ItineraryDto extends createZodDto(itinerarySchema) {}
class ListItinerariesQueryDto extends createZodDto(listItinerariesQuerySchema) {}
class ListItinerariesResponseDto extends createZodDto(listItinerariesResponseSchema) {}

/** `/v1/itineraries` (ADR-030 §6): the athlete's private Itineraries. */
@Controller("itineraries")
@UseGuards(SessionGuard)
export class ItinerariesController {
  constructor(private readonly itineraries: ItinerariesService) {}

  /**
   * Distance and elevation gain a save would store for these Waypoints
   * and Legs; writes nothing. `503` (retryable) when an elevation provider
   * fails. Only the global throttler limit applies.
   */
  @Post("metrics-preview")
  @HttpCode(HttpStatus.OK)
  @ZodResponse({ status: 200, type: ItineraryMetricsDto })
  previewMetrics(@Body() body: ItineraryMetricsPreviewRequestDto): Promise<ItineraryMetrics> {
    return this.itineraries.previewMetrics(body);
  }

  /**
   * Saves a new Itinerary (id generated by the app) and returns it. `201`
   * on creation, `200` when the same athlete replays it (nothing written),
   * `409` if the id is someone else's, `422` invalid name, sport or
   * geometry, `503` (retryable) when an elevation provider fails.
   */
  @Post()
  @ZodResponse({ status: 201, type: ItineraryDto, description: "Created" })
  @ApiResponse({ status: 200, type: ItineraryDto.Output, description: "Replayed by the same athlete: nothing written" })
  async create(
    @Body() body: CreateItineraryRequestDto,
    @CurrentUser() user: AuthenticatedUser,
    @Res({ passthrough: true }) response: Response,
  ): Promise<Itinerary> {
    const result = await this.itineraries.create(user.userId, body);
    response.status(result.created ? HttpStatus.CREATED : HttpStatus.OK);
    return result.itinerary;
  }

  /** The athlete's Itineraries, most recently updated first (keyset cursor). */
  @Get()
  @ZodResponse({ status: 200, type: ListItinerariesResponseDto })
  list(@Query() query: ListItinerariesQueryDto, @CurrentUser() user: AuthenticatedUser): Promise<ListItinerariesResponse> {
    return this.itineraries.list(user.userId, query);
  }

  /** One of the athlete's Itineraries; `404` if unknown or someone else's. */
  @Get(":id")
  @ZodResponse({ status: 200, type: ItineraryDto })
  get(@Param("id", ParseUUIDPipe) itineraryId: string, @CurrentUser() user: AuthenticatedUser): Promise<Itinerary> {
    return this.itineraries.get(user.userId, itineraryId);
  }
}
