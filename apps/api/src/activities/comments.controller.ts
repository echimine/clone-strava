import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  ParseUUIDPipe,
  Patch,
  Post,
  Query,
  Res,
  UseGuards,
} from "@nestjs/common";
import { ApiResponse } from "@nestjs/swagger";
import type { Response } from "express";
import { createZodDto, ZodResponse } from "nestjs-zod";
import {
  commentSchema,
  createCommentRequestSchema,
  listCommentsQuerySchema,
  listCommentsResponseSchema,
  updateCommentRequestSchema,
  type ActivityComment,
  type ListCommentsResponse,
} from "@repo/contracts";
import { EngagementService } from "@repo/core/engagement";
import { CurrentUser } from "../auth/current-user.decorator.js";
import { SessionGuard, type AuthenticatedUser } from "../auth/session.guard.js";
import { CommentAssembler } from "./comment-assembler.js";

class CommentDto extends createZodDto(commentSchema) {}
class CreateCommentRequestDto extends createZodDto(createCommentRequestSchema) {}
class ListCommentsQueryDto extends createZodDto(listCommentsQuerySchema) {}
class ListCommentsResponseDto extends createZodDto(listCommentsResponseSchema) {}
class UpdateCommentRequestDto extends createZodDto(updateCommentRequestSchema) {}

/**
 * `/v1/activities/:id/comments` (ADR-034 §3). Every route answers
 * `404 activity_not_found` when the viewer cannot see the Activity and
 * `409 activity_not_commentable` when it is not processed.
 */
@Controller("activities/:id/comments")
@UseGuards(SessionGuard)
export class CommentsController {
  constructor(
    private readonly engagement: EngagementService,
    private readonly assembler: CommentAssembler,
  ) {}

  /** The newest page (or the one older than `before`) in chronological order. */
  @Get()
  @ZodResponse({ status: 200, type: ListCommentsResponseDto })
  async list(
    @Param("id", ParseUUIDPipe) activityId: string,
    @Query() query: ListCommentsQueryDto,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<ListCommentsResponse> {
    const page = await this.engagement.listComments(user.userId, activityId, query);
    return { items: await this.assembler.assemble(page.items), previousCursor: page.previousCursor };
  }

  /** One comment; `404 comment_not_found` when unknown, deleted or on another Activity. */
  @Get(":commentId")
  @ZodResponse({ status: 200, type: CommentDto })
  async getOne(
    @Param("id", ParseUUIDPipe) activityId: string,
    @Param("commentId", ParseUUIDPipe) commentId: string,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<ActivityComment> {
    return this.assembler.assembleOne(await this.engagement.getComment(user.userId, activityId, commentId));
  }

  /**
   * Adds a comment (id generated by the app). `201` on creation, `200`
   * when the same author replays it on the same Activity (nothing written),
   * `409 comment_id_conflict` if the id is used otherwise.
   */
  @Post()
  @ZodResponse({ status: 201, type: CommentDto, description: "Created" })
  @ApiResponse({ status: 200, type: CommentDto.Output, description: "Replayed by the same author: nothing written" })
  async add(
    @Param("id", ParseUUIDPipe) activityId: string,
    @Body() body: CreateCommentRequestDto,
    @CurrentUser() user: AuthenticatedUser,
    @Res({ passthrough: true }) response: Response,
  ): Promise<ActivityComment> {
    const result = await this.engagement.addComment(user.userId, activityId, body);
    response.status(result.created ? HttpStatus.CREATED : HttpStatus.OK);
    return this.assembler.assembleOne(result.comment);
  }

  /** Edits the body; the comment's author only (`403 not_comment_author`), no time limit. */
  @Patch(":commentId")
  @ZodResponse({ status: 200, type: CommentDto })
  async edit(
    @Param("id", ParseUUIDPipe) activityId: string,
    @Param("commentId", ParseUUIDPipe) commentId: string,
    @Body() body: UpdateCommentRequestDto,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<ActivityComment> {
    return this.assembler.assembleOne(await this.engagement.editComment(user.userId, activityId, commentId, body.body));
  }

  /**
   * Soft delete by the comment's author or the Activity's author (`403`
   * otherwise). Idempotent: an already deleted comment answers `204` too.
   */
  @Delete(":commentId")
  @HttpCode(HttpStatus.NO_CONTENT)
  @ApiResponse({ status: 204, description: "Deleted, or already deleted" })
  remove(
    @Param("id", ParseUUIDPipe) activityId: string,
    @Param("commentId", ParseUUIDPipe) commentId: string,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<void> {
    return this.engagement.deleteComment(user.userId, activityId, commentId);
  }
}
