import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  ParseUUIDPipe,
  Post,
  Res,
  UseGuards,
} from "@nestjs/common";
import { ApiResponse } from "@nestjs/swagger";
import type { Response } from "express";
import { createZodDto, ZodResponse } from "nestjs-zod";
import {
  activityDetailSchema,
  completeActivityResponseSchema,
  createActivityRequestSchema,
  createActivityResponseSchema,
  renewUploadUrlResponseSchema,
  type ActivityDetail,
  type ActivitySummary,
  type CompleteActivityResponse,
  type CreateActivityResponse,
  type RenewUploadUrlResponse,
} from "@repo/contracts";
import { ActivitiesService, type ActivityRecord } from "@repo/core/activities";
import { CurrentUser } from "../auth/current-user.decorator.js";
import { SessionGuard, type AuthenticatedUser } from "../auth/session.guard.js";
import { RequestId } from "../common/request-id.decorator.js";

class CreateActivityRequestDto extends createZodDto(createActivityRequestSchema) {}
class CreateActivityResponseDto extends createZodDto(createActivityResponseSchema) {}
class RenewUploadUrlResponseDto extends createZodDto(renewUploadUrlResponseSchema) {}
class CompleteActivityResponseDto extends createZodDto(completeActivityResponseSchema) {}
class ActivityDetailDto extends createZodDto(activityDetailSchema) {}

/** `ActivityRecord` (core) -> `ActivitySummary` (contracts wire shape). */
function toActivitySummary(activity: ActivityRecord): ActivitySummary {
  return {
    id: activity.id,
    sportTypeCode: activity.sportTypeCode,
    visibility: activity.visibility,
    processingStatus: activity.processingStatus,
  };
}

/** `/v1/activities` (ADR-019 §1-4, ADR-031 §13): creation flow of a recorded activity, author's read. */
@Controller("activities")
@UseGuards(SessionGuard)
export class ActivitiesController {
  constructor(private readonly activitiesService: ActivitiesService) {}

  /**
   * Creates a `pending` activity (id generated by the app) and returns a
   * 15-minute pre-signed `PUT` URL for its gzipped trace v2, to send with
   * `Content-Type: application/gzip`. `201` on creation, `200` when the
   * same athlete replays it (new URL while `pending`, none afterwards),
   * `409` if the id is someone else's, `422` inactive sport, `endedAt` not
   * after `startedAt` or duration under the sport's minimum. The
   * provisional values are never taken as official.
   */
  @Post()
  @ZodResponse({ status: 201, type: CreateActivityResponseDto, description: "Created" })
  @ApiResponse({
    status: 200,
    type: CreateActivityResponseDto.Output,
    description: "Replayed by the same athlete",
  })
  async create(
    @Body() body: CreateActivityRequestDto,
    @CurrentUser() user: AuthenticatedUser,
    @Res({ passthrough: true }) response: Response,
  ): Promise<CreateActivityResponse> {
    const result = await this.activitiesService.create(user.userId, body);
    response.status(result.created ? HttpStatus.CREATED : HttpStatus.OK);
    return { activity: toActivitySummary(result.activity), upload: result.uploadUrl };
  }

  /** The author's activity whatever its state, official values once `processed`; `404` for anyone else. */
  @Get(":id")
  @ZodResponse({ status: 200, type: ActivityDetailDto })
  get(
    @Param("id", ParseUUIDPipe) activityId: string,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<ActivityDetail> {
    return this.activitiesService.getOwn(user.userId, activityId);
  }

  /**
   * Hard delete of the author's activity while `pending` or `failed` (ADR-031 §13), with its
   * trace: `204`. `409 not_deletable` in any other state; `404` if unknown or someone else's.
   */
  @Delete(":id")
  @HttpCode(HttpStatus.NO_CONTENT)
  @ApiResponse({ status: 204, description: "Deleted" })
  async remove(
    @Param("id", ParseUUIDPipe) activityId: string,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<void> {
    await this.activitiesService.delete(user.userId, activityId);
  }

  /** New upload URL while the activity is `pending` (expired URL, ADR-008), `409 not_pending` otherwise. */
  @Post(":id/upload-url")
  @HttpCode(HttpStatus.OK)
  @ZodResponse({ status: 200, type: RenewUploadUrlResponseDto })
  renewUploadUrl(
    @Param("id", ParseUUIDPipe) activityId: string,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<RenewUploadUrlResponse> {
    return this.activitiesService.requestUploadUrl(user.userId, activityId);
  }

  /**
   * The trace is in the bucket: `pending` -> `processing` and the worker
   * computes the official values. `409 trace_missing` / `trace_too_large`
   * after a `HEAD` of the trace; replays on a `processing` / `processed`
   * activity are `202` without effect; `409 activity_failed` once `failed`.
   */
  @Post(":id/complete")
  @HttpCode(HttpStatus.ACCEPTED)
  @ZodResponse({ status: 202, type: CompleteActivityResponseDto })
  async complete(
    @Param("id", ParseUUIDPipe) activityId: string,
    @CurrentUser() user: AuthenticatedUser,
    @RequestId() requestId: string | undefined,
  ): Promise<CompleteActivityResponse> {
    const activity = await this.activitiesService.complete(user.userId, activityId, requestId);
    return { activity: toActivitySummary(activity) };
  }
}
